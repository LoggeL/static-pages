def clean_pdf_text(text: str) -> str:
    # Verbinde Silbentrennungen am Zeilenende (z. B. "Ausbil-\ndung" -> "Ausbildung")
    text = re.sub(r"-\s*\n\s*", "", text)
    # Normalisiere mehrfache Leerzeichen
    lines = [re.sub(r"[ \t]+", " ", line).strip() for line in text.splitlines()]
    return "\n".join(line for line in lines if line)


def extract_pages() -> dict[int, str]:
    reader = PdfReader(str(PDF_PATH))
    pages: dict[int, str] = {}
    for idx, page in enumerate(reader.pages, start=1):
        pages[idx] = clean_pdf_text(page.extract_text() or "")
    return pages


def build_excerpt(pages: dict[int, str], page_nums: list[int]) -> str:
    chunks = []
    for p in page_nums:
        txt = pages.get(p, "").strip()
        if txt:
            chunks.append(f"[PDF Seite {p}]\n{txt}")
    return "\n\n".join(chunks)


