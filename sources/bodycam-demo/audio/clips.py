# Schnittliste für fetch_sounds.py.
# Jeder Eintrag: name, id (YouTube), start/end (Sekunden im Original; start = ungefährer Onset,
# der exakte Einsatz wird im Fenster [start-pre, start+search] gesucht), dazu Verarbeitungsoptionen:
#   hp/hp2/lp (Hz), eq [(f, Breite, dB)], nr (afftdn-Stärke), af (roher ffmpeg-Filter),
#   snap (Onset suchen, Standard True), len (feste Länge ab Onset), gate_head [mute_s, ramp_s] (Schwanz-Layer),
#   tail/floor (Auto-Kürzung), fi/fo (Fades), loop (Crossfade-Sekunden), stereo, lufs/peak (Normalisierung), br.
# full=False: nur den Abschnitt laden (lange Videos).

def C(name, id, start, end, *presets, **kw):
    d = dict(name=name, id=id, start=start, end=end)
    for p in presets:
        d.update(p)
    d.update(kw)
    return d

