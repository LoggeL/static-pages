export function referenceStrokes(key, footprint) {
  const { size, strokes } = traced[key];
  return strokes.map(line => line.map(([x, y]) => [x * footprint.length / (size[0] - 1), y * footprint.width / (size[1] - 1)]));
}

export function referenceMarkup(key, footprint) {
  const paths = referenceStrokes(key, footprint).map(line => 'M' + line.map(p => p.map(n => n.toFixed(3)).join(',')).join('L')).join('');
  return '<g data-layer="sketch" fill="none" stroke="#a82f75" stroke-opacity=".82" stroke-width=".032" stroke-linejoin="round" stroke-linecap="round"><title>Nachgezeichnete Skizzenkonturen (' + key.toUpperCase() + ')</title><path d="' + paths + '"/></g>';
}
